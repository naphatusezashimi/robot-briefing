_KEYWORDS = [
    "อยู่ที่ไหน", "อยู่ไหน", "ตรงไหน", "ที่ไหน",
    "ไปยังไง", "ไปทางไหน", "ไปยัง", "เดินทางไป",
    "ทางไป", "เส้นทาง", "แผนที่", "ที่ตั้ง",
    "ตำบล", "หมู่บ้าน", "วัด", "ที่ว่าการอำเภอ",
]


def wants_map(text: str) -> bool:
    """คืน True ถ้าข้อความมีคีย์เวิร์ดที่บ่งบอกว่าถามเรื่องตำแหน่ง/ทาง"""
    for kw in _KEYWORDS:
        if kw in text:
            return True
    return False
