    "อยู่ที่ไหน", "อยู่ไหน", "ตรงไหน", "ที่ไหน",
    "ไปยังไง", "ไปทางไหน", "ไปยัง", "เดินไป",
    "ทางไป", "เส้นทาง", "แผนผัง", "แผนที่",
    "อาคาร", "ตึก", "ห้อง", "สนาม",
    "โรงอาหาร", "หอประชุม", "ป้อมยาม",
